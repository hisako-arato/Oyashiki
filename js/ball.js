// 0:30 閉宴
export function closeLines(s) {
  const st = s.ballStats || { served: 0, missed: 0 };
  return [
    '0時半。客たちが、笑いながら帰っていく。玄関の外に、迎えの車のライトが連なった。',
    '旦那様は「月下の庭」を自ら壁から下ろし、書斎の隠し部屋へ戻させた。',
    `（今夜の配膳：運んだ料理 ${st.served}皿${st.missed ? `、待たせた客 ${st.missed}人` : ''}）`,
  ];
}

// 配膳の最後に、旦那様の心象へ（運んだ皿と待たせた客で決まる）
export function settleBall(s) {
  const st = s.ballStats || { served: 0, missed: 0 };
  const d = Math.max(-6, Math.min(6, Math.round(st.served * 0.5 - st.missed * 1.5)));
  s.trust = clamp(s.trust + d);
  return d;
}

