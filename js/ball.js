// 舞踏会の最中に話しかけたとき（人物ごと）
export function ballTalk(s, id, min) {
  const after = t => min >= t;
  switch (id) {
    case 'father': return [[F, '「客の皿を切らすな。今夜は、鷹宮の名に懸けて完璧に頼むぞ」']];
    case 'mother': return after(AT.reiko) ? ['お母様は、こちらを見もしなかった。視線の先には、深紅の仮面の女がいる。']
      : [[M, '「……今夜は話しかけないで。あの人の『お客様』が来るのよ」']];
    case 'daughter': return [[D, s.flags.d_close ? '「執事さん。……あとで、一曲くらい付き合ってよね」' : '「仮面って、息苦しい。……早く終わらないかな」']];
    case 'reiko': return [[RK, '「あら、素敵な執事さん。……鷹宮さんの奥様には、内緒にしておいてね」']];
    case 'dealer': return [[DL, '「（眼鏡の奥で、壁の絵から目を離さずに）……良い保存状態だ。25日の朝、予定どおり伺いますよ」']];
    case 'caterer':
      if (s.flags.caterer_friend) { setFlag(s, 'caterer_met'); return [[C, '「……雫ちゃんのお兄さん、ですよね。話は聞いてます」'], [C, '「裏の白いバン、片付けが済むまで停めておきます。……何か運ぶ物があれば」']]; }
      return [[C, '「お疲れさまです！ 次の料理、すぐ上がります！」']];
    case 'red':
      if (after(AT.serve) && (s.aff.red >= 40 || s.flags.r_parcel)) { setFlag(s, 'dealer_seen'); return [[R, '「……執事さん。あの眼鏡の人」'], [R, '「夜中に、勝手口から来る車の人。……額縁の荷物を持ってくる人と、同じ顔」']]; }
      return [[R, '「……料理、どんどん上がる。運んで」']];
    case 'blue': return [[BL, s.flags.forgery_start ? '「お客様の仮面、みんなわたしが絵付けしたんですよ！ ……あの壁の絵も、ちゃんと見ておかなきゃ」' : '「お客様の仮面、みんなわたしが絵付けしたんですよ！」']];
    case 'white': return [[W, '「招待客の中に、うちの会社の役員が三人。……この会の費用、どこから出ているんでしょうね」']];
    case 'black': return [[K, '「執事さん、手が止まっています」'], '（すれ違いざま、雫が小声で付け足した）', [S, '「……絵、見た？ お母さんの好きだった絵。……ちゃんと、取り戻そうね」']];
    case 'guard': return [[ '巡回員', '「今夜は舞踏会の警備です。客が帰ったら、夜通し巡回に入ります」']];
    default: return ['（今は話している場合ではない）'];
  }
}

